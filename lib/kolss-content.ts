function breadcrumb(path: string, label: string) {
  const items = [
    {
      "@type": "ListItem",
      position: 1,
      name: "Головна",
      item: `${siteUrl}/`,
    },
  ];

  if (path !== "/") {
    items.push({
      "@type": "ListItem",
      position: 2,
      name: label,
      item: `${siteUrl}${path}`,
    });
  }

  return {
    "@type": "BreadcrumbList",
    "@id": `${siteUrl}${path === "/" ? "" : path}#breadcrumb`,
    itemListElement: items,
  };
}

function faqJsonLd(path: string, faq: PageContent["faq"]) {
  return {
    "@type": "FAQPage",
    "@id": `${siteUrl}${path === "/" ? "" : path}#faq`,
    mainEntity: faq.slice(0, 3).map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.answer,
      },
    })),
  };
}

